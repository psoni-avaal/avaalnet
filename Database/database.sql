CREATE TABLE IF NOT EXISTS public.products (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name character varying(120) NOT NULL,
    price numeric(18,2) NOT NULL CHECK (price > 0),
    image_url character varying(255)
);

ALTER TABLE public.products
    ADD COLUMN IF NOT EXISTS image_url character varying(255);

CREATE TABLE IF NOT EXISTS public.orders (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id integer NOT NULL,
    customer_name character varying(120) NOT NULL,
    email character varying(180) NOT NULL,
    phone character varying(30) NOT NULL,
    address character varying(500) NOT NULL,
    quantity integer NOT NULL DEFAULT 1 CHECK (quantity > 0),
    total_amount numeric(18,2) NOT NULL,
    created_at timestamp with time zone NOT NULL DEFAULT now(),
    status character varying(50) NOT NULL DEFAULT 'Pending',
    CONSTRAINT fk_orders_product FOREIGN KEY (product_id) REFERENCES public.products(id) ON DELETE CASCADE
);

INSERT INTO public.products (name, price)
SELECT seed.name, seed.price
FROM (VALUES
    ('Keyboard', 1500.00::numeric),
    ('Mouse', 1200.00::numeric),
    ('Monitor', 18500.00::numeric),
    ('Laptop Stand', 2500.00::numeric)
) AS seed(name, price)
WHERE NOT EXISTS (
    SELECT 1 FROM public.products existing WHERE existing.name = seed.name
);
