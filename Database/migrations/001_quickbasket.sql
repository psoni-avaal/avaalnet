CREATE TABLE IF NOT EXISTS public.products (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name character varying(150) NOT NULL,
    price numeric(10,2) NOT NULL CHECK (price >= 0),
    image_url character varying(255)
);

CREATE TABLE IF NOT EXISTS public.categories (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name character varying(100) NOT NULL UNIQUE
);

ALTER TABLE public.products
    ADD COLUMN IF NOT EXISTS category_id integer;

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1
        FROM pg_constraint
        WHERE conname = 'products_category_id_fkey'
          AND conrelid = 'public.products'::regclass
    ) THEN
        ALTER TABLE public.products
            ADD CONSTRAINT products_category_id_fkey
            FOREIGN KEY (category_id) REFERENCES public.categories(id) ON DELETE SET NULL;
    END IF;
END
$$;

CREATE TABLE IF NOT EXISTS public.store_users (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name character varying(100) NOT NULL,
    email character varying(254) NOT NULL,
    password_hash text NOT NULL,
    address character varying(500) NOT NULL DEFAULT '',
    created_at timestamp with time zone NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX IF NOT EXISTS ux_store_users_email_lower
    ON public.store_users (lower(email));

CREATE TABLE IF NOT EXISTS public.orders (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id integer NOT NULL REFERENCES public.products(id) ON DELETE CASCADE,
    customer_name character varying(120) NOT NULL,
    email character varying(180) NOT NULL,
    phone character varying(30) NOT NULL,
    address character varying(500) NOT NULL,
    quantity integer NOT NULL DEFAULT 1 CHECK (quantity > 0),
    total_amount numeric(18,2) NOT NULL,
    created_at timestamp with time zone NOT NULL DEFAULT now(),
    status character varying(50) NOT NULL DEFAULT 'Pending'
);

ALTER TABLE public.products
    ADD COLUMN IF NOT EXISTS unit character varying(40) NOT NULL DEFAULT '1 item',
    ADD COLUMN IF NOT EXISTS stock_quantity integer NOT NULL DEFAULT 25,
    ADD COLUMN IF NOT EXISTS original_price numeric(10,2);

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1
        FROM pg_constraint
        WHERE conname = 'products_stock_quantity_check'
          AND conrelid = 'public.products'::regclass
    ) THEN
        ALTER TABLE public.products
            ADD CONSTRAINT products_stock_quantity_check CHECK (stock_quantity >= 0);
    END IF;
END
$$;

ALTER TABLE public.store_users
    ADD COLUMN IF NOT EXISTS is_admin boolean NOT NULL DEFAULT false;

CREATE INDEX IF NOT EXISTS ix_products_category_id
    ON public.products (category_id);

CREATE TABLE IF NOT EXISTS public.customer_orders (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id integer NOT NULL REFERENCES public.store_users(id) ON DELETE RESTRICT,
    customer_name character varying(120) NOT NULL,
    phone character varying(30) NOT NULL,
    email character varying(254) NOT NULL,
    address character varying(500) NOT NULL,
    delivery_instructions character varying(500),
    subtotal numeric(12,2) NOT NULL CHECK (subtotal >= 0),
    total_amount numeric(12,2) NOT NULL CHECK (total_amount >= 0),
    status character varying(50) NOT NULL DEFAULT 'Pending',
    created_at timestamp with time zone NOT NULL DEFAULT now()
);

ALTER TABLE public.customer_orders
    ADD COLUMN IF NOT EXISTS email character varying(254) NOT NULL DEFAULT '';
ALTER TABLE public.customer_orders
    ALTER COLUMN subtotal TYPE numeric(18,2),
    ALTER COLUMN total_amount TYPE numeric(18,2);

CREATE TABLE IF NOT EXISTS public.customer_order_items (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id integer NOT NULL REFERENCES public.customer_orders(id) ON DELETE CASCADE,
    product_id integer REFERENCES public.products(id) ON DELETE SET NULL,
    product_name character varying(120) NOT NULL,
    image_url character varying(255),
    unit_price numeric(10,2) NOT NULL CHECK (unit_price >= 0),
    quantity integer NOT NULL CHECK (quantity > 0),
    line_total numeric(12,2) NOT NULL CHECK (line_total >= 0)
);

ALTER TABLE public.customer_order_items
    ALTER COLUMN line_total TYPE numeric(18,2);

CREATE INDEX IF NOT EXISTS ix_customer_orders_user_created
    ON public.customer_orders (user_id, created_at DESC);
CREATE INDEX IF NOT EXISTS ix_customer_order_items_order
    ON public.customer_order_items (order_id);

